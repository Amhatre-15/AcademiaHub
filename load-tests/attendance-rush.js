/**
 * AcademiaHub — Phase 17 Load Test: 9:00 AM Attendance Rush
 * ─────────────────────────────────────────────────────────────────────────────
 * Simulates a campus-wide lecture start: 1,200 students submit the rotating
 * HMAC QR payload for the same live session inside a 45-second window.
 *
 * Each virtual user uses a distinct pre-signed JWT and recomputes the 1-second
 * HMAC token with `k6/crypto`, exactly like the real browser client.
 *
 * Prerequisites
 *   1. Backend + database running, and an E2E fixture created:
 *        npm run e2e:seed --prefix backend
 *   2. Token pool generated:
 *        npm run e2e:load-users --prefix backend
 *   3. A live session with an active START checkpoint. Either start one from
 *      the Faculty cockpit, or let `setup()` create the checkpoint for you.
 *
 * Run
 *   k6 run load-tests/attendance-rush.js
 *   k6 run -e API_URL=https://staging.example.com load-tests/attendance-rush.js
 *
 * Environment
 *   API_URL                 default http://localhost:5000
 *   FACULTY_USERNAME        default e2e_faculty
 *   FACULTY_PASSWORD        default E2e@Test123
 *   LOAD_TOTAL              total attendance submissions (default 1200)
 *   LOAD_DURATION           default 45s
 *   TOKENS_FILE             default tokens.json (next to this script)
 */

import http from 'k6/http';
import crypto from 'k6/crypto';
import exec from 'k6/execution';
import { check, fail } from 'k6';
import { Counter, Rate, Trend } from 'k6/metrics';

const API_URL = __ENV.API_URL ?? 'http://localhost:5000';
const FACULTY_USERNAME = __ENV.FACULTY_USERNAME ?? 'e2e_faculty';
const FACULTY_PASSWORD = __ENV.FACULTY_PASSWORD ?? 'E2e@Test123';
const TOTAL = Number(__ENV.LOAD_TOTAL ?? 1200);
const DURATION = __ENV.LOAD_DURATION ?? '45s';

// `open()` must run in the init context; the file is generated by
// `npm run e2e:load-users --prefix backend`.
let TOKENS = [];
try {
  TOKENS = JSON.parse(open('./tokens.json'));
} catch {
  // Validated in setup() with a friendly message.
}

// ── Custom metrics ───────────────────────────────────────────────────────────
const attendanceSuccess = new Rate('attendance_success');
const attendanceLatency = new Trend('attendance_latency', true);
const duplicateSubmissions = new Counter('attendance_duplicates');
const expiredTokens = new Counter('attendance_expired_tokens');

export const options = {
  scenarios: {
    attendance_rush: {
      executor: 'constant-arrival-rate',
      // 1,200 iterations per 45-second time unit = exactly 1,200 students.
      rate: TOTAL,
      timeUnit: DURATION,
      duration: DURATION,
      preAllocatedVUs: 200,
      maxVUs: 600,
      gracefulStop: '10s',
      tags: { scenario: 'attendance_rush' },
    },
  },
  thresholds: {
    // Targets from future_plan.md §3.4 (tune for remote/cloud DB latency).
    'http_req_duration{scenario:attendance_rush}': ['p(95)<120', 'p(99)<300'],
    attendance_success: ['rate>0.99'],
    http_req_failed: ['rate<0.01'],
  },
};

/**
 * Authenticate as faculty, find (or open) an attendance checkpoint, and hand
 * the secret to the VUs. Only the first run needs a fresh session; re-seed
 * with `npm run e2e:seed --prefix backend` between benchmark runs.
 */
export function setup() {
  if (!TOKENS.length) {
    fail(
      'load-tests/tokens.json is missing or empty. Run:\n' +
        '  npm run e2e:load-users --prefix backend'
    );
  }

  const jsonHeaders = { 'Content-Type': 'application/json' };
  const login = http.post(
    `${API_URL}/api/auth/login`,
    JSON.stringify({ username: FACULTY_USERNAME, password: FACULTY_PASSWORD }),
    { headers: jsonHeaders, tags: { name: 'faculty_login' } }
  );

  if (login.status !== 200) {
    fail(`Faculty login failed (${login.status}): ${login.body}`);
  }

  const facultyToken = login.json('token');
  const authHeaders = { ...jsonHeaders, Authorization: `Bearer ${facultyToken}` };

  let session = http.get(`${API_URL}/api/faculty/sessions/active`, {
    headers: authHeaders,
    tags: { name: 'get_active_session' },
  }).json();

  if (!session || !session.id) {
    fail(
      'No ACTIVE session found. Start a class from the Faculty cockpit first, or run:\n' +
        '  npm run e2e:seed --prefix backend   (then start a class)'
    );
  }

  let checkpoint = (session.attendanceCheckpoints ?? []).find((c) => c.isActive);

  if (!checkpoint) {
    const generated = http.post(
      `${API_URL}/api/faculty/sessions/${session.id}/attendance/generate`,
      JSON.stringify({ checkpointType: 'START', durationSeconds: 300 }),
      { headers: authHeaders, tags: { name: 'generate_checkpoint' } }
    );

    if (generated.status !== 201) {
      fail(
        `Could not open a checkpoint (${generated.status}): ${generated.body}\n` +
          'Reset the fixture with: npm run e2e:seed --prefix backend'
      );
    }
    checkpoint = generated.json();
  }

  if (!checkpoint.qrSecret) {
    fail('Checkpoint secret missing. Ensure you are authenticated as the owning faculty.');
  }

  console.log(
    `[load] session=${session.id} checkpoint=${checkpoint.id} ` +
      `students=${TOKENS.length} total=${TOTAL} window=${DURATION}`
  );

  return {
    sessionId: session.id,
    checkpointId: checkpoint.id,
    checkpointType: checkpoint.checkpointType,
    secret: checkpoint.qrSecret,
  };
}

export default function submitAttendance(data) {
  // `iterationInTest` is globally unique, so each of the 1,170 requests uses a
  // different student (as long as the token pool is large enough).
  const student = TOKENS[exec.scenario.iterationInTest % TOKENS.length];

  // Recomputed every iteration: the QR token rotates once per second.
  const t = Math.floor(Date.now() / 1000);
  const hash = crypto
    .hmac('sha256', data.secret, `${data.checkpointId}:${t}`, 'hex')
    .slice(0, 16);

  const payload = JSON.stringify({
    sid: data.sessionId,
    cid: data.checkpointId,
    t,
    hash,
    type: data.checkpointType,
  });

  const response = http.post(
    `${API_URL}/api/student/sessions/${data.sessionId}/attendance/submit`,
    JSON.stringify({ qrPayload: payload }),
    {
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${student.token}`,
      },
      tags: { name: 'attendance_submit' },
    }
  );

  attendanceLatency.add(response.timings.duration);
  attendanceSuccess.add(response.status === 201);

  if (response.status === 201) {
    check(response, { 'attendance accepted': (r) => r.status === 201 });
    return;
  }

  // Classify expected negative outcomes instead of failing the whole run.
  let error = '';
  try {
    error = response.json('error') ?? '';
  } catch {
    error = response.body ?? '';
  }

  if (/already submitted/i.test(error)) duplicateSubmissions.add(1);
  if (/expired/i.test(error)) expiredTokens.add(1);

  check(response, {
    'attendance accepted or gracefully rejected': (r) =>
      r.status === 201 || r.status === 400 || r.status === 404,
  });
}
